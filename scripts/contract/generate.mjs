// Regenerates contract/openapi.json and src/api/generated/schema.ts from the vendored bundle
// (research R6, R7). Run through `npm run contract:generate`; never edit the outputs by hand.
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '../..')
const bin = (name) => join(root, 'node_modules/.bin', name)
const run = (cmd, args) =>
  execFileSync(cmd, args, {
    cwd: root,
    stdio: 'inherit',
    env: { ...process.env, REDOCLY_TELEMETRY: 'off' },
  })

run(bin('redocly'), ['bundle', 'contract/openapi.yaml', '--ext', 'json', '-o', 'contract/openapi.json'])

mkdirSync(join(root, 'src/api/generated'), { recursive: true })
run(bin('openapi-typescript'), [
  'contract/openapi.yaml',
  '-o',
  'src/api/generated/schema.ts',
  '--root-types',
  '--root-types-no-schema-prefix',
  '--enum-values',
  '--read-write-markers',
  '--alphabetize',
])

// openapi-typescript 7.13 annotates some `--enum-values` arrays with types that do not compile:
// read-only enums (`$Read<…>` inside `FlattenedDeepRequired`) and `oneOf` members it renders as
// `unknown` (for example `Mailbox.rateLimitSource` and `MailboxMailSettingsBulkActionRequest` of
// mailcow-rest-v2 features 003 and 005). The declarations stay fully typed for the code that
// imports them; only the diagnostics inside this generated file are switched off.
const schemaPath = join(root, 'src/api/generated/schema.ts')
const schema = readFileSync(schemaPath, 'utf8')
const marker = '// @ts-nocheck: generated by scripts/contract/generate.mjs (see the comment there)\n'
if (!schema.startsWith(marker)) writeFileSync(schemaPath, marker + schema)
