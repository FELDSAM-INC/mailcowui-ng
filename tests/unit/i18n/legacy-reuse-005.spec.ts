// T150: the approved form map is the input, not a second hand-maintained list of UI labels.
import { readFileSync, readdirSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

import { lt } from '@/i18n'
import { flagLabel } from '@/i18n/problems'
import type { LegacyKey } from '@/i18n/legacy'
import { duplicateLegacyMeanings, flatten, type Messages } from '../../../scripts/i18n/lib.mjs'

const read = (path: string) => readFileSync(join(process.cwd(), path), 'utf8')
const plan = read('specs/005-account-self-service/plan.md')
  .split('### Legacy form map (T010a, 2026-10-19)')[1]!
  .split('#### Part 3: deviations needing a decision')[0]!
const parity = read('specs/005-account-self-service/spec.md')
  .split('### Legacy Parity')[1]!
  .split('\n## ')[0]!
const roots =
  'user|tfa|login|edit|add|mailbox|danger|success|info|warning|footer|admin|acl|datatables|header'
const planned = [
  ...new Set(
    [...`${plan}\n${parity}`.matchAll(new RegExp('`((?:' + roots + ')\\.[a-z_]+)`', 'g'))]
      .map((match) => match[1]!)
      .filter((key) => !/\.(php|twig)$/.test(key)),
  ),
]
const snapshot = JSON.parse(read('src/i18n/snapshot/lang.en-gb.json')) as Messages
const texts = flatten(snapshot)
const source = readdirSync('src', { recursive: true })
  .filter((file) => /\.(ts|vue)$/.test(String(file)) && !String(file).includes('generated/'))
  .map((file) =>
    read(`src/${String(file)}`)
      .replace(/^\s*\/\/.*$/gm, '')
      .replace(/\/\*[\s\S]*?\*\//g, ''),
  )
  .join('\n')

// Each exception is a documented replacement/removal, never a silent missing translation.
const superseded: Record<string, string> = {
  'edit.previous': 'Owner removed Previous page links from all account sections',
  'user.alias_create_random':
    'Owner moved spam alias creation to a separate form with a Create spam alias button',
  'user.mailbox': 'D1 flat hub, no old dropdown',
  'user.mailbox_general': 'D1 overview leads the hub; no General tab',
  'user.mailbox_details': 'D1 Details content moves into the overview',
  'user.user_settings':
    'Form-map section 1 permits header.user_settings for the single hub heading',
  'user.show_sieve_filters':
    'D1/D16 active-script section uses its legacy user.active_sieve heading',
  'edit.admin': 'D9 one own-password screen uses user.change_password for every role',
  'edit.password_repeat': 'D9 one own-password form uses user.new_password_repeat',
  'user.new_password_description': 'Form-map missing upstream key, never rendered',
  'login.password_mismatch': 'Form-map missing upstream key, danger.password_mismatch replaces it',
  'tfa.error_code': 'D12 approved plain-language WebAuthn error messages',
  'tfa.reload_retry': 'D12 approved plain-language WebAuthn retry actions',
  'success.recovery_email_sent': 'D2 avoids revealing account existence',
  'danger.password_reset_invalid_user': 'D2 avoids revealing account existence',
  'user.force_pw_update': 'D1 blocking pending-actions screen uses user.pw_update_required',
  'user.password': 'D3 app passwords are generated by the server, no typed password field',
  'user.password_repeat': 'D3 app passwords are generated by the server',
  'mailbox.sieve_preset_header': 'FR-096 presets belong to UI013',
  'mailbox.insert_preset': 'FR-096 presets belong to UI013',
  'danger.redis_error': 'Form-map Part2 uses typed dependency messages without raw exceptions',
  'danger.app_passwd_id_invalid': 'Form-map Part2 common 404 uses shared not-found state',
  'user.alias_full_date':
    'Spec explicitly replaces the legacy format pattern with locale formatting',
  'datatables.expand_all': 'Form-map explicitly excludes DataTables child-row controls',
  'datatables.collapse_all': 'Form-map explicitly excludes DataTables child-row controls',
}

describe('UI005 legacy form map', () => {
  it('every planned legacy key exists in the bundled English snapshot, except two documented missing keys', () => {
    expect(planned.length).toBeGreaterThan(250)
    expect(planned.filter((key) => !texts.has(key)).sort()).toEqual([
      'login.password_mismatch',
      'user.new_password_description',
    ])
  })

  it('each retained legacy key is referenced by key, including permission labels composed at runtime', () => {
    const dynamicFlags: Record<string, string> = {
      'acl.filters': 'filters',
    }
    for (const [key, flag] of Object.entries(dynamicFlags))
      expect(flagLabel(flag)).toBe(lt(key as LegacyKey))
    const missing = planned.filter(
      (key) =>
        !superseded[key] &&
        !dynamicFlags[key] &&
        !source.includes(`'${key}'`) &&
        !source.includes(`"${key}"`),
    )
    expect(missing).toEqual([])
  })

  it('UI005 adds no unreviewed copies of legacy values to its new strings', () => {
    const feature = JSON.parse(read('src/i18n/messages/account/en-gb.json')) as Messages
    // Plan section12 explicitly distinguishes a Sieve filter from admin.filter (LDAP search);
    // “Type” is the legacy table's hard-coded heading, unlike add.sieve_type (form label).
    const semanticExceptions = ['filters.columns.type', 'filters.form.title']
    expect(
      duplicateLegacyMeanings(feature, snapshot).filter(
        ({ key }) => !semanticExceptions.includes(key),
      ),
    ).toEqual([])
    const shared = JSON.parse(read('src/i18n/messages/en-gb.json')) as Messages
    expect(
      duplicateLegacyMeanings(shared, snapshot).filter(({ key }) =>
        /^(selfService|enums\.(appPasswordProtocol|sieveFilterKind|pushoverSound)|validation\.(preHashedPassword|tooLongBytes))/.test(
          key,
        ),
      ),
    ).toEqual([])
  })
})
